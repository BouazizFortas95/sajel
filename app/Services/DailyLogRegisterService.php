<?php

namespace App\Services;

use App\Enums\DailyLogStatus;
use App\Models\Classroom;
use App\Models\DailyLog;
use App\Models\Subject;
use App\Models\User;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Foundation\ViteException;
use Illuminate\Support\Facades\Vite;
use Spatie\Browsershot\Browsershot;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Builds the official class-register view and, when needed, renders it to a
 * server-side PDF with headless Chrome so Arabic shaping and Tailwind layouts
 * stay identical to the browser version.
 */
class DailyLogRegisterService
{
    /**
     * Return only completed logs visible to the given user.
     *
     * The bulk action already receives Filament's scoped records, but the
     * query is repeated here so direct calls cannot bypass the completed-only
     * rule or a teacher's ownership scope.
     *
     * @param  array<int, int|string>  $ids
     * @return Collection<int, DailyLog>
     */
    public function completedLogs(array $ids, User $user): Collection
    {
        return DailyLog::query()
            ->with([
                'schedule.user',
                'schedule.subject',
                'schedule.classroom.level.educationPhase',
                'schedule.classroom.groups',
                'schedule.group.classroom.level.educationPhase',
                'schedule.group.classroom.groups',
            ])
            ->whereKey($ids)
            ->where('status', DailyLogStatus::Completed->value)
            ->when(
                ! $user->isAdmin(),
                fn (Builder $query): Builder => $query->forTeacher($user),
            )
            ->orderBy('date')
            ->orderBy('id')
            ->get();
    }

    /**
     * Build one standalone class-register sheet per resolved classroom.
     *
     * @param  Collection<int, DailyLog>  $logs
     * @return array{
     *     logs: Collection<int, DailyLog>,
     *     registers: \Illuminate\Support\Collection<int, array<string, mixed>>,
     *     teacherName: string,
     *     academicYear: string,
     *     autoPrint: bool,
     *     inlineCss: bool
     * }
     */
    public function viewData(
        Collection $logs,
        User $user,
        bool $autoPrint = true,
        bool $inlineCss = false,
    ): array {
        $registers = $this->registerSections($logs);

        $teacherNames = $logs
            ->pluck('schedule.user.name')
            ->filter()
            ->unique()
            ->implode(' / ');

        $academicYears = $registers
            ->pluck('academicYear')
            ->filter()
            ->unique()
            ->implode(' / ');

        return [
            'logs' => $logs,
            'registers' => $registers,
            'teacherName' => $teacherNames !== '' ? $teacherNames : $user->name,
            'academicYear' => $academicYears !== '' ? $academicYears : $this->currentAcademicYear(),
            'autoPrint' => $autoPrint,
            'inlineCss' => $inlineCss,
        ];
    }

    /**
     * Render the register and inline Vite's compiled Tailwind stylesheet.
     *
     * Browsershot receives an HTML string, so a public asset URL can fail when
     * Chrome cannot resolve the application host. The compiled CSS is already
     * generated by Vite, so embedding it removes that network dependency.
     *
     * @param  Collection<int, DailyLog>  $logs
     */
    public function pdfHtml(Collection $logs, User $user): string
    {
        $css = $this->compiledCss();

        $html = view('print.register', $this->viewData(
            logs: $logs,
            user: $user,
            autoPrint: false,
            inlineCss: $css !== null,
        ))->render();

        return $css === null ? $html : $this->inlineCss($html, $css);
    }

    /**
     * Render the register to a PDF and return it as a download response.
     *
     * The PDF is generated before the response is returned so Browsershot
     * failures can be reported by the Filament action instead of surfacing
     * while Livewire is already streaming the download.
     *
     * @param  Collection<int, DailyLog>  $logs
     */
    public function pdfResponse(Collection $logs, User $user): StreamedResponse
    {
        $pdf = $this->browsershot($this->pdfHtml($logs, $user))->pdf();

        return response()->streamDownload(
            function () use ($pdf): void {
                echo $pdf;
            },
            'دفتر-النصوص-'.now()->format('Y-m-d').'.pdf',
            ['Content-Type' => 'application/pdf'],
        );
    }

    /**
     * Classroom is the official owner of a register. A schedule may target a
     * whole classroom or one of its groups, so resolve both shapes to the same
     * classroom before grouping.
     *
     * @param  Collection<int, DailyLog>  $logs
     * @return \Illuminate\Support\Collection<int, array<string, mixed>>
     */
    private function registerSections(Collection $logs): \Illuminate\Support\Collection
    {
        $registers = $logs
            ->groupBy(fn (DailyLog $log): string => (string) ($this->resolveClassroom($log)?->getKey() ?? 'unassigned'))
            ->map(fn (Collection $registerLogs): array => $this->makeRegisterSection($registerLogs))
            ->sortBy(fn (array $register): string => (string) ($register['classroom']?->name ?? 'zzz'))
            ->values();

        return $registers->isEmpty()
            ? collect([$this->emptyRegisterSection()])
            : $registers;
    }

    /**
     * @param  Collection<int, DailyLog>  $logs
     * @return array<string, mixed>
     */
    private function makeRegisterSection(Collection $logs): array
    {
        $firstLog = $logs->first();
        $classroom = $firstLog instanceof DailyLog ? $this->resolveClassroom($firstLog) : null;
        $dates = $logs->pluck('date')->filter()->sort()->values();

        $academicYear = $classroom?->academic_year;

        if (blank($academicYear)) {
            $academicYear = $logs
                ->map(fn (DailyLog $log): ?string => $this->resolveClassroom($log)?->academic_year)
                ->filter()
                ->first();
        }

        return [
            'classroom' => $classroom,
            'logs' => $logs,
            'phase' => $classroom?->level?->educationPhase,
            'levelName' => $classroom?->level?->name,
            'academicYear' => $academicYear ?: $this->currentAcademicYear(),
            'from' => $dates->first(),
            'to' => $dates->last(),
            'count' => $logs->count(),
            'groups' => $classroom?->groups?->sortBy('name')->values() ?? collect(),
            'teachers' => $this->teacherAssignments($logs),
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function emptyRegisterSection(): array
    {
        return [
            'classroom' => null,
            'logs' => new Collection,
            'phase' => null,
            'levelName' => null,
            'academicYear' => $this->currentAcademicYear(),
            'from' => null,
            'to' => null,
            'count' => 0,
            'groups' => collect(),
            'teachers' => collect(),
        ];
    }

    /**
     * Unique teacher/subject pairs assigned to this class register.
     *
     * @param  Collection<int, DailyLog>  $logs
     * @return \Illuminate\Support\Collection<int, array{teacher: ?User, subject: ?Subject, count: int}>
     */
    private function teacherAssignments(Collection $logs): \Illuminate\Support\Collection
    {
        return $logs
            ->groupBy(function (DailyLog $log): string {
                $schedule = $log->schedule;

                return ($schedule?->user?->getKey() ?? 'none').'|'.($schedule?->subject?->getKey() ?? 'none');
            })
            ->map(function (Collection $assignmentLogs): array {
                $schedule = $assignmentLogs->first()?->schedule;

                return [
                    'teacher' => $schedule?->user,
                    'subject' => $schedule?->subject,
                    'count' => $assignmentLogs->count(),
                ];
            })
            ->sortBy(fn (array $assignment): string => ($assignment['teacher']?->name ?? '').'|'.($assignment['subject']?->name ?? ''))
            ->values();
    }

    private function resolveClassroom(DailyLog $log): ?Classroom
    {
        return $log->schedule?->classroom ?? $log->schedule?->group?->classroom;
    }

    private function browsershot(string $html): Browsershot
    {
        $browsershot = Browsershot::html($html)
            ->format('A4')
            ->showBackground()
            ->margins(10, 10, 10, 10)
            ->setOption('preferCSSPageSize', true)
            ->waitUntilNetworkIdle()
            ->timeout(120);

        if (is_dir(base_path('node_modules'))) {
            $browsershot->setNodeModulePath(base_path('node_modules'));
        }

        foreach ([
            'node_binary' => 'setNodeBinary',
            'npm_binary' => 'setNpmBinary',
            'chrome_path' => 'setChromePath',
        ] as $configKey => $method) {
            $value = config("services.browsershot.{$configKey}");

            if (filled($value)) {
                $browsershot->{$method}($value);
            }
        }

        return $browsershot;
    }

    private function inlineCss(string $html, string $css): string
    {
        $baseUrl = e(rtrim((string) config('app.url'), '/').'/');

        return str_replace(
            '</head>',
            '<base href="'.$baseUrl.'"><style>'.str_replace('</style', '<\/style', $css).'</style></head>',
            $html,
        );
    }

    private function compiledCss(): ?string
    {
        try {
            return Vite::content('resources/css/app.css');
        } catch (ViteException) {
            return null;
        }
    }

    private function currentAcademicYear(): string
    {
        $startYear = now()->month >= 9 ? now()->year : now()->year - 1;

        return "{$startYear}/".($startYear + 1);
    }
}
